// 智记能耗 - 油品标号显示工具
//
// 背景：从小熊油耗导入的数据里，柴油标号是 "0#"，而本 App 手动录入的选项是 "0#柴油"。
// 同一个东西两种写法，列表里看着不一致。
//
// 处理原则：
//   - 只做「显示」和「编辑时归一化」，不擅自批量改库里的历史值
//   - 柴油标号（0# / -10# / -20# / -35#）统一补上"柴油"两个字
//   - 汽油标号（92# / 95# / 98#）保持原样

/// 把原始油品标号转成展示用的文字
///
/// `0#` → `0#柴油`；`92#` 保持 `92#`；空值返回 null
String? fuelTypeLabel(String? raw) {
  if (raw == null) return null;
  final s = raw.trim();
  if (s.isEmpty) return null;
  // 柴油只有「0#」和「负数标号」：0# / -10# / -20# / -35#
  // 注意：93# / 92# / 95# / 98# 是【汽油】标号，不能加"柴油"
  if (RegExp(r'^(0|-[0-9]+)#$').hasMatch(s)) return '$s柴油';
  return s;
}

/// 编辑时的归一化：把 "0#" 这类原始值转成下拉框里存在的选项
///
/// 下拉选项是 ['92#', '95#', '98#', '0#柴油', '其他']，
/// 如果直接把导入的 "0#" 塞进去，Dropdown 找不到匹配项会显示空白。
String? normalizeFuelType(String? raw) => fuelTypeLabel(raw);
